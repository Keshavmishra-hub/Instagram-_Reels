MUSIC_EXT = (".mp3", ".wav", ".m4a", ".aac", ".flac", ".ogg")


def _music_mood(pid: str, store: ProjectStore) -> str:
    project = store.project(pid)
    mood = project.settings.music_mood
    if mood and mood != "auto":
        return mood
    sb = store.storyboard(pid)
    if sb and sb.music_mood:
        return sb.music_mood
    return get_style(project.settings.style).music_mood


def _sections(pid: str, store: ProjectStore) -> list[tuple[float, float, str]]:
    script = store.script(pid)
    tl = store.timeline(pid)
    sec = {b.id: b.section for b in script.beats}
    out = []
    for i, bt in enumerate(tl.beats):
        end = tl.beats[i + 1].start if i + 1 < len(tl.beats) else tl.duration
        out.append((bt.start, end, sec.get(bt.beat_id, "story")))
    return out


def _sfx_events(props: dict) -> list[tuple[float, str, float]]:
    events = []
    scenes = props["scenes"]
    for i, sc in enumerate(scenes):
        if i > 0 and sc["transition"] in ("whip", "slide_up", "slide_left", "zoom", "wipe"):
            events.append((sc["start"], "whoosh", 0.32))
        if sc["section"] == "payoff" and (i == 0 or scenes[i - 1]["section"] != "payoff"):
            events.append((sc["start"], "riser", 0.28))
            events.append((sc["start"], "impact", 0.34))
        for o in sc["overlays"]:
            events.append((o["at"], "pop", 0.22))
        if sc["kind"] == "stat":
            events.append((sc["start"] + 0.25, "pop", 0.18))
    return events


def prepare_audio(pid: str, store: ProjectStore, props: dict, log: Callable[[str], None] = print) -> Path:
    d = store.dir(pid)
    project = store.project(pid)
    tl = store.timeline(pid)
    mood = _music_mood(pid, store)
    music_path: Optional[Path] = None
    override = next((p for p in sorted((d / "audio").glob("music_override.*")) if p.suffix.lower() in MUSIC_EXT), None)
    if override:
        log(f"Using user-supplied music: {override.name}")
        music_path = override
    elif mood != "none":
        log(f"Composing original score (mood: {mood}) ...")
        music_path = write_music(d / "audio/music.wav", tl.duration, mood, _sections(pid, store), seed=abs(hash(pid)) % 1000)
    sfx_path = write_sfx_track(d / "audio/sfx.wav", tl.duration, _sfx_events(props))
    log("Mastering audio (voice processing, ducking, -14 LUFS) ...")
    stats = master_audio(
        d / tl.narration_file, d / "audio/mix.wav", music=music_path, sfx=sfx_path,
        music_gain_db=project.settings.music_level_db, duration=tl.duration, stems_dir=d / "audio/stems",
    )
    store.write_json(pid, "audio/mix_loudness.json", stats)
    return d / "audio/mix.wav"


def write_caption_files(pid: str, store: ProjectStore) -> None:
    tl = store.timeline(pid)
    store.write_text(pid, "output/captions.srt", to_srt(tl.words))
    store.write_text(pid, "output/captions.vtt", to_vtt(tl.words))


def write_credits(pid: str, store: ProjectStore) -> str:
    lib = store.assets(pid)
    sb = store.storyboard(pid)
    used = {sc.visual.asset_id for sc in sb.scenes} | {sc.background.asset_id for sc in sb.scenes if sc.background}
    lines = ["CREDITS & LICENCES", ""]
    for a in lib.assets:
        if a.id not in used:
            continue
        lines.append(f"- {a.kind.capitalize()}: {a.title or a.provider_id} by {a.author or 'unknown'} via {a.provider} - {a.license} ({a.license_url}) {a.page_url}")
    music_meta = store.dir(pid) / "audio/music.json"
    if music_meta.exists():
        lines.append("- Music: original score generated by ReelForge for this reel (no third-party rights).")
    elif any((store.dir(pid) / "audio").glob("music_override.*")):
        lines.append("- Music: user-supplied track (licence held by the user).")
    lines += [
        "- Maps: Natural Earth (public domain) via world-atlas.",
        "- Icons: Lucide (ISC licence).",
        "- Fonts: Anton, Inter, Montserrat, Poppins, Teko, Noto Sans (SIL Open Font License).",
        "- Narration: synthetic voice (Kokoro-82M, Apache-2.0) unless another provider is noted in project settings.",
    ]
    text = "\n".join(lines) + "\n"
    store.write_text(pid, "output/credits.txt", text)
    return text


def render_cover(pid: str, store: ProjectStore, props: dict, s: Settings = default_settings, log: Callable[[str], None] = print) -> Path:
    d = store.dir(pid)
    cp = cover_props(pid, store, props)
    store.write_json(pid, "render/cover_props.json", cp)
    out = d / "output/cover.jpg"
    sc = cp.get("scene")
    frame = min(880, int(round((sc["end"] - sc["start"]) * 30 * 0.85))) if sc else 0
    remotion.run(d / "render/cover_props.json", still=out, frame=frame, composition="Cover", assets_root=d, log=log, s=s)
    with Image.open(out) as im:  # how it will look in the 3:4 profile grid
        w, h = im.size
        gh = int(w * 4 / 3)
        top = (h - gh) // 2
        im.crop((0, top, w, top + gh)).save(d / "output/cover_grid_preview.jpg", quality=90)
    return out


def render_reel(
    pid: str,
    store: ProjectStore,
    s: Settings = default_settings,
    log: Callable[[str], None] = print,
    progress: Callable[[float], None] = lambda p: None,
) -> dict:
    d = store.dir(pid)
    (d / "render").mkdir(exist_ok=True)
    (d / "output").mkdir(exist_ok=True)
    props = build_props(pid, store, s)
    store.write_json(pid, "render/props.json", props)
    mix = prepare_audio(pid, store, props, log)
    progress(0.05)
    log(f"Rendering {len(props['scenes'])} scenes at 1080x1920 / 30 fps with Remotion ...")
    silent = d / "render/video_silent.mp4"
    remotion.run(d / "render/props.json", out=silent, assets_root=d, progress=lambda p: progress(0.05 + 0.85 * p), log=log, s=s)
    script = store.script(pid)
    final = mux(silent, mix, d / "output/reel.mp4", title=script.title if script else "", s=s)
    progress(0.93)
    log("Rendering cover image ...")
    try:
        render_cover(pid, store, props, s, log)
    except Exception as e:  # cover failure should not lose the render
        log(f"Cover render failed: {e}")
    write_caption_files(pid, store)
    write_credits(pid, store)
    # storyboard thumbnails straight from the final video (what the viewer will actually see)
    thumbs = d / "render/thumbs"
    thumbs.mkdir(exist_ok=True)
    for sc in props["scenes"]:
        mid = sc["start"] + (sc["end"] - sc["start"]) * 0.6
        try:
            extract_frame(final, mid, thumbs / f"{sc['id']}.jpg", s)
        except Exception:
            pass
    progress(1.0)
    log(f"Render complete: {final}")
    return {"video": str(final), "cover": str(d / "output/cover.jpg")}


def render_scene_preview(pid: str, scene_id: str, store: ProjectStore, s: Settings = default_settings, log: Callable[[str], None] = print) -> Path:
    """Low-res preview of a single scene with its narration, for quick iteration."""
    d = store.dir(pid)
    props = build_props(pid, store, s)
    sc = next((x for x in props["scenes"] if x["id"] == scene_id), None)
    if sc is None:
        raise ValueError(f"scene {scene_id} not found (is the voice-over up to date?)")
    store.write_json(pid, "render/props.json", props)
    a, b = int(sc["start"] * 30), max(int(sc["start"] * 30) + 1, int(sc["end"] * 30) - 1)
    silent = d / f"render/preview_{scene_id}_silent.mp4"
    remotion.run(d / "render/props.json", out=silent, assets_root=d, scale=0.5, frames=(a, b), log=log, s=s)
    out = d / f"render/preview_{scene_id}.mp4"
    import subprocess

    subprocess.run([
        s.ffmpeg_bin, "-y", "-hide_banner", "-loglevel", "error", "-i", str(silent),
        "-ss", f"{sc['start']:.3f}", "-t", f"{sc['end'] - sc['start']:.3f}", "-i", str(d / "audio/narration.wav"),
        "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a", "128k", "-shortest", str(out),
    ], check=True)
    silent.unlink(missing_ok=True)
    return out


def render_storyboard_stills(pid: str, store: ProjectStore, s: Settings = default_settings, log: Callable[[str], None] = print) -> list[Path]:
    """Half-resolution still of each scene (before the full render) for storyboard review."""
    d = store.dir(pid)
    props = build_props(pid, store, s)
    store.write_json(pid, "render/props.json", props)
    out_dir = d / "render/stills"
    out_dir.mkdir(parents=True, exist_ok=True)
    outs = []
    for sc in props["scenes"]:
        f = int((sc["start"] + (sc["end"] - sc["start"]) * 0.7) * 30)
        out = out_dir / f"{sc['id']}.jpg"
        remotion.run(d / "render/props.json", still=out, frame=f, assets_root=d, scale=0.5, log=log, s=s)
        outs.append(out)
    return outs


def copy_sample(pid: str, store: ProjectStore, dest: Path) -> None:
    """Copy the deliverables of a project into a folder (used for the committed sample)."""
    d = store.dir(pid)
    dest.mkdir(parents=True, exist_ok=True)
    for rel in ["research.md", "research.json", "script.md", "script.json", "storyboard.json", "output"]:
        src = d / rel
        if src.is_dir():
            shutil.copytree(src, dest / rel, dirs_exist_ok=True)
        elif src.exists():
            shutil.copy2(src, dest / rel)
    (dest / "README.txt").write_text(json.dumps({"project": pid}, indent=2), encoding="utf-8")
